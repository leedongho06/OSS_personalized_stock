def get_recent_business_day() -> str:
    for i in range(1, 10):
        date = (datetime.today() - timedelta(days=i)).strftime("%Y%m%d")
        df = stock.get_market_ohlcv_by_date(date, date, "005930")
        if not df.empty:
            return date
    return (datetime.today() - timedelta(days=7)).strftime("%Y%m%d")


def build_stocks_csv():
    """
    주식 데이터를 수집하여 CSV로 저장하는 함수입니다.
    """
    import os  # os 모듈이 상단에 없다면 여기에 추가해주세요
    
    today = datetime.today()
    base_date = get_recent_business_day()
    print(f"기준일: {base_date}")

    records = []
    for i, (ticker, name, sector) in enumerate(TOP100_TICKERS):
        print(f"[{i+1}/{len(TOP100_TICKERS)}] {name} ({ticker})")

        # PER, PBR
        try:
            fundamental = stock.get_market_fundamental_by_date(
                base_date, base_date, ticker
            )
            if not fundamental.empty:
                per = float(fundamental["PER"].iloc[0])
                pbr = float(fundamental["PBR"].iloc[0])
            else:
                per, pbr = None, None
        except Exception:
            per, pbr = None, None

        # 이동평균, 거래량
        try:
            start = (today - timedelta(days=30)).strftime("%Y%m%d")
            ohlcv = stock.get_market_ohlcv_by_date(start, base_date, ticker)
            if not ohlcv.empty:
                ma_20 = round(float(ohlcv["종가"].mean()), 2)
                volume = int(ohlcv["거래량"].mean())
            else:
                ma_20, volume = None, None
        except Exception:
            ma_20, volume = None, None

        # 변동성
        if per is None:
            volatility = "중"
        elif per > 25:
            volatility = "고"
        elif per > 15:
            volatility = "중"
        else:
            volatility = "저"

        records.append({
            "ticker": ticker,
            "name": name,
            "sector": sector,
            "per": per,
            "pbr": pbr,
            "ma_20": ma_20,
            "volume": volume,
            "volatility": volatility,
        })

        time.sleep(0.2)

    # 💡 [KeyError 방어] 데이터가 아예 수집되지 않았을 경우를 대비
    if not records:
        print("수집된 데이터가 없습니다. 저장 과정을 건너뜁니다.")
        return

    df = pd.DataFrame(records)

    # 결측값 처리
    for col in ["per", "pbr", "ma_20", "volume"]:
        df[col] = pd.to_numeric(df[col], errors="coerce")
        df[col] = df[col].fillna(df[col].median())

    # 💡 [AssertionError 방어] 폴더가 없으면 생성하고 저장
    os.makedirs("data", exist_ok=True)
    
    df.to_csv("data/stocks.csv", index=False, encoding="utf-8-sig")
    print(f"\n저장 완료: data/stocks.csv ({len(df)}개 종목)")
    print(df.head())

if __name__ == "__main__":
    build_stocks_csv()
